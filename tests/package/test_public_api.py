def test_package_root_matches_exact_frozen_2x_public_allowlist() -> None:
    assert tuple(openrund.__all__) == EXPECTED_PUBLIC_API
    assert tuple(openrund.__all__) == tuple(sorted(EXPECTED_PUBLIC_API))


def test_advanced_operator_types_live_on_named_subpackage() -> None:
    import openrund.operator as operator

    assert operator.CommandResultData.__module__ == "openrund.operator._model"
    assert operator.RunInspectionData.__module__ == "openrund.operator._model"
    assert "CommandResultData" not in openrund.__all__
